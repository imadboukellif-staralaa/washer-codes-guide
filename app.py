@app.route("/api/search")
def api_search():
    brand = request.args.get("brand", "").strip()
    wtype = request.args.get("wtype", "").strip()
    code_query = " ".join(request.args.get("code", "").strip().upper().split())

    matches = []
    for entry in CODES_DB:
        if brand and entry["brand"].lower() != brand.lower():
            continue
        if wtype and wtype not in entry["types"]:
            continue

        normalized_codes = [" ".join(c.upper().split()) for c in entry["codes"]]
        if code_query in normalized_codes:
            matches.append(entry)

    return jsonify({"matches": matches})


